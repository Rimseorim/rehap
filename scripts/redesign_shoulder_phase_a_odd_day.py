# 키핑/손목은 type만 수정 (내용은 유지)
kp = next(m for m in d['movements'] if m['id'] == 'kipping')
kp_wrist = next(ps for ps in kp['pain_sites'] if ps['id'] == 'wrist')
kp_ca = next(c for c in kp_wrist['causes'] if c['id'] == 'cause-a')
pa = kp_ca['route']['stages'][0].get('phase_a', [])
for e in pa:
    if e.get('set') == 'a':
        name = e.get('name', '')
        if '스트레칭' in name or '굴곡' in name or '신전' in name:
            e['type'] = '스트레칭'
        else:
            e['type'] = '활성화'

# 나머지 4개 cause 홀수날 교체
for mv in d['movements']:
    for ps in mv['pain_sites']:
        for c in ps.get('causes', []):
            key = (mv['id'], ps['id'], c['id'])
            if key in odd_day_sets:
                pa = c['route']['stages'][0].get('phase_a', [])
                # 짝수날 보존, 홀수날만 교체
                ab_exs = [e for e in pa if e.get('set') == 'a_b']
                new_a = odd_day_sets[key]
                c['route']['stages'][0]['phase_a'] = new_a + ab_exs

