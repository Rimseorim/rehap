def transform_file(filepath):
    with open(filepath, encoding='utf-8') as f:
        data = json.load(f)

    movement_id = data.get('id', '')
    converted = 0
    skipped = 0

    for ps in data.get('pain_sites', []):
        pain_site_id = ps.get('id', '')
        for cause in ps.get('causes', []):
            cause_id = cause.get('id', '')
            stages = cause.get('route', {}).get('stages', [])

            if len(stages) <= 3:
                skipped += 1
                continue

            # Stage 1: merge first 3 stages' exercises
            first_duration = stages[0].get('duration', '')
            merged_exercises = []
            for st in stages[:3]:
                merged_exercises.extend(st.get('exercises', []))

            stage1 = {
                "id": "stage-1",
                "name": "준비",
                "exercises": merged_exercises,
                "duration": first_duration
            }

            # Stage 2: reassessment
            stage2 = dict(REASSESSMENT)

            # Stage 3: tips
            tips = get_tips(movement_id, pain_site_id, cause_id)
            stage3 = {
                "id": "stage-3",
                "name": "운동 복귀",
                "type": "tips",
                "duration": "꾸준히 유지",
                "tips": tips
            }

            cause['route']['stages'] = [stage1, stage2, stage3]
            converted += 1

    with open(filepath, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    return converted, skipped

if __name__ == '__main__':
    files = glob.glob('data/movements/*.json')
    files = [f for f in files if 'manifest' not in f]
    total_converted = 0
